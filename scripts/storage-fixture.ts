// Writes a database fixture: an SQL dump of a database created by this build's migrations, with synthetic rows in
// every table (L-071: one fixture per released minor; upgrade tests load each one and migrate it). Generate it for a
// minor before its release and never regenerate it afterwards.
//
//   node --conditions=source scripts/storage-fixture.ts 0.2
