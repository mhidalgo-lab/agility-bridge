function literal(value: unknown): string {
  if (value === null) return 'NULL';
  if (typeof value === 'number' || typeof value === 'bigint') return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
}

export async function dumpFixture(): Promise<string> {
  const db = new DatabaseSync(':memory:');
  const storage = await openSqlStorage(createSqliteDriver(db), { now: () => T });
  await seed(storage);
  const objects = db
    .prepare('SELECT type, name, sql FROM sqlite_schema WHERE sql IS NOT NULL ORDER BY rowid')
    .all() as { type: string; name: string; sql: string }[];
  const lines = [
    `-- agility-bridge database fixture: schema version ${MIGRATIONS.length}. Generated by scripts/storage-fixture.ts.`,
    '-- Synthetic data only. Frozen once its release ships (L-071).',
    'PRAGMA foreign_keys = OFF;',
    'BEGIN;',
  ];
  for (const o of objects.filter((x) => x.type === 'table')) lines.push(`${o.sql};`);
  for (const o of objects.filter((x) => x.type === 'table')) {
    for (const row of db.prepare(`SELECT * FROM "${o.name}" ORDER BY rowid`).all() as Record<
      string,
      unknown
    >[]) {
      const cols = Object.keys(row);
      lines.push(
        `INSERT INTO ${o.name} (${cols.join(', ')}) VALUES (${cols.map((c) => literal(row[c])).join(', ')});`,
      );
    }
  }
  for (const o of objects.filter((x) => x.type !== 'table')) lines.push(`${o.sql};`);
  lines.push('COMMIT;', '');
  db.close();
  return lines.join('\n');
}

if (import.meta.main) {
  const minor = process.argv[2];
  if (!minor || !/^\d+\.\d+$/.test(minor)) {
    console.error('usage: node --conditions=source scripts/storage-fixture.ts <minor, e.g. 0.2>');
    process.exit(2);
  }
  const out = new URL(`../packages/storage-sqlite/test/fixtures/databases/${minor}.sql`, import.meta.url);
  writeFileSync(out, await dumpFixture(), { flag: 'wx' });
  console.error(`wrote ${out.pathname}`);
}
