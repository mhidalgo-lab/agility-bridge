// P1-13 (L-134): docs/reference/tools.md generated from the tool registry, so the reference never drifts from the
// code. Defaults come from the schemas (L-150). Run: pnpm docs:tools   Check (CI): node scripts/tool-reference.ts --check
import { readFileSync, writeFileSync } from 'node:fs';
import {
  annotationsFor,
  CORE_TOOLS,
  type ToolDefinition,
  withCachedJsonSchema,
} from '../packages/core/src/index.ts';

const OUT = new URL('../docs/reference/tools.md', import.meta.url);

type Json = Record<string, unknown>;

const cell = (s: string) => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function typeOf(schema: Json): string {
  if (Array.isArray(schema['enum']))
    return (schema['enum'] as unknown[]).map((v) => `\`${String(v)}\``).join(' | ');
  if (Array.isArray(schema['anyOf'])) return (schema['anyOf'] as Json[]).map(typeOf).join(' or ');
  if (schema['type'] === 'array') {
    const items = (schema['items'] ?? {}) as Json;
    const max = typeof schema['maxItems'] === 'number' ? ` (≤ ${schema['maxItems']})` : '';
    return `${typeOf(items)}[]${max}`;
  }
  if (schema['type'] === 'object') return 'object';
  const range = [
    typeof schema['minimum'] === 'number' ? `≥ ${schema['minimum']}` : '',
    typeof schema['maximum'] === 'number' && (schema['maximum'] as number) < 1e15
      ? `≤ ${schema['maximum']}`
      : '',
  ].filter(Boolean);
  return `${String(schema['type'] ?? 'any')}${range.length > 0 ? ` (${range.join(', ')})` : ''}`;
}

function section(tool: ToolDefinition): string {
  const input = withCachedJsonSchema(tool.inputSchema as never)['~standard'].jsonSchema.input({
    target: 'draft-2020-12',
  }) as Json;
  const props = (input['properties'] ?? {}) as Record<string, Json>;
  const required = new Set((input['required'] as string[] | undefined) ?? []);
  const a = annotationsFor(tool);
  const lines = [
    `## \`${tool.name}\``,
    '',
    `**${tool.title}** · group \`${tool.group}\` · ${tool.kind} · cost ${tool.cost} Agility request${tool.cost === 1 ? '' : 's'} at most`,
    '',
    tool.description,
    '',
    `Annotations: read-only ${a.readOnlyHint}, destructive ${a.destructiveHint}, idempotent ${a.idempotentHint}, open world ${a.openWorldHint}.`,
    '',
  ];
  if (Object.keys(props).length === 0) {
    lines.push('No arguments.', '');
  } else {
    lines.push('| Argument | Type | Required | Default | Description |', '|---|---|---|---|---|');
    for (const [name, p] of Object.entries(props)) {
      const def = p['default'] === undefined ? '' : `\`${JSON.stringify(p['default'])}\``;
      lines.push(
        `| \`${name}\` | ${cell(typeOf(p))} | ${required.has(name) ? 'yes' : ''} | ${def} | ${cell(String(p['description'] ?? ''))} |`,
      );
    }
    lines.push('');
  }
  if (tool.outputSchema !== undefined) {
    const output = withCachedJsonSchema(tool.outputSchema as never)['~standard'].jsonSchema.output({
      target: 'draft-2020-12',
    }) as Json;
    const fields = Object.keys((output['properties'] ?? {}) as Json);
    lines.push(
      `\`structuredContent\`: ${fields.map((f) => `\`${f}\``).join(', ')} (open: more fields may be added).`,
      '',
    );
  }
  return lines.join('\n');
}

export function render(): string {
  const tools = [...CORE_TOOLS];
  const head = [
    '<!-- Generated by scripts/tool-reference.ts from the tool registry: do not edit. Run `pnpm docs:tools`. -->',
    '',
    '# Tool reference',
    '',
    `${tools.length} tools. What every result looks like: [output formats](../guide/output-formats.md); the plan and the`,
    'later phases: [tool catalogue](tool-catalogue.md). Costs are worst cases with a cold metadata cache.',
    '',
    '| Tool | Group | Cost | Title |',
    '|---|---|---|---|',
    ...tools.map((t) => `| [\`${t.name}\`](#${t.name}) | ${t.group} | ${t.cost} | ${t.title} |`),
    '',
  ];
  return `${[...head, ...tools.map(section)].join('\n').trimEnd()}\n`;
}

if (import.meta.main) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8');
    if (current !== text) {
      console.error('docs/reference/tools.md is out of date: run pnpm docs:tools and commit it.');
      process.exitCode = 1;
    }
  } else {
    writeFileSync(OUT, text);
    console.error('wrote docs/reference/tools.md');
  }
}
