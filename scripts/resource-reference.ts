// P6-09 (L-133, L-153): docs/reference/resources.md generated from the resource manifest, so the reference never drifts
// from what the server registers. Run: pnpm docs:resources   Check (CI): node scripts/resource-reference.ts --check
import { readFileSync, writeFileSync } from 'node:fs';
import { RESOURCE_MANIFEST } from '../packages/core/src/index.ts';

const OUT = new URL('../docs/reference/resources.md', import.meta.url);

const cell = (s: string) => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function render(): string {
  const rows = RESOURCE_MANIFEST.map(
    (r) =>
      `| \`${r.uri}\` | ${cell(r.title)} | ${r.uses.map((t) => `\`${t}\``).join(', ')} | ${r.source} | \`${r.mimeType}\` |`,
  );
  const sections = RESOURCE_MANIFEST.flatMap((r) => [
    `## \`${r.id}\``,
    '',
    `\`${r.uri}\``,
    '',
    r.description,
    '',
    `Served through: ${r.uses.map((t) => `[\`${t}\`](tools.md#${t})`).join(', ')}. Offered only when ${r.uses.length === 1 ? 'that tool is' : 'all of those tools are'} allowed for the workspace and grant.${r.uri.includes('{') ? ' A template: `resources/list` shows one URI per readable value.' : ''}`,
    '',
  ]);
  return `${[
    '<!-- Generated by scripts/resource-reference.ts from the resource manifest: do not edit. Run `pnpm docs:resources`. -->',
    '',
    '# Resource reference',
    '',
    `${RESOURCE_MANIFEST.length} resources. Reference material an agent reads on demand (\`resources/read\`). Each one is served through`,
    'the tool handlers named below, so a read has the same request budget, limits, metadata cache, scope rules, untrusted-data',
    'envelope and audit entry (action `resource:<id>`) as the tool call it stands for. A resource whose tools are not allowed for the',
    'workspace or grant does not exist: it is not listed and reading it fails. The plan: [tool catalogue](tool-catalogue.md#resources-phase-6).',
    '',
    '| URI | Title | Served through | Content | MIME type |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    ...sections,
  ]
    .join('\n')
    .trimEnd()}\n`;
}

if (import.meta.main) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8');
    if (current !== text) {
      console.error('docs/reference/resources.md is out of date: run pnpm docs:resources and commit it.');
      process.exitCode = 1;
    }
  } else {
    writeFileSync(OUT, text);
    console.error('wrote docs/reference/resources.md');
  }
}
