// Generates docs/reference/admin-api.md from the admin API's OpenAPI document (P2-09, L-134: references come from
// code). Run: pnpm docs:admin-api   Check (tests): the test compares the committed file with render().
import { writeFileSync } from 'node:fs';
import { createAdminApi } from '../packages/http-app/src/index.ts';

const OUT = new URL('../docs/reference/admin-api.md', import.meta.url);

interface Schema {
  type?: string | string[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  enum?: unknown[];
  anyOf?: Schema[];
  const?: unknown;
  $ref?: string;
  minimum?: number;
  maximum?: number;
  maxLength?: number;
}

interface Operation {
  tags?: string[];
  summary?: string;
  requestBody?: { content?: { 'application/json'?: { schema?: Schema } } };
  parameters?: { name: string; in: string }[];
  responses?: Record<string, { content?: { 'application/json'?: { schema?: Schema } } }>;
}

function typeOf(s: Schema | undefined): string {
  if (s === undefined) return '';
  if (s.$ref !== undefined) return s.$ref.split('/').at(-1) ?? '';
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum !== undefined) return s.enum.map((e) => JSON.stringify(e)).join(' \\| ');
  if (s.anyOf !== undefined) return s.anyOf.map(typeOf).join(' \\| ');
  const t = Array.isArray(s.type) ? s.type.join(' \\| ') : (s.type ?? 'object');
  if (t === 'array') return `${typeOf(s.items)}[]`;
  return t;
}

function fields(s: Schema | undefined): string {
  if (s?.properties === undefined) return '—';
  const required = new Set(s.required ?? []);
  return Object.entries(s.properties)
    .map(([k, v]) => `\`${k}\`${required.has(k) ? '' : '?'}: ${typeOf(v)}`)
    .join('<br>');
}

export function render(): string {
  const api = createAdminApi({
    services: undefined as never,
    storage: undefined as never,
    tools: new Map(),
    audit: undefined as never,
    onChange: () => {},
    authenticate: async () => null,
    clientIp: () => 'unknown',
    logger: undefined as never,
    clock: { now: () => 0 },
  });
  const doc = api.getOpenAPI31Document({
    openapi: '3.1.0',
    info: { title: 'agility-bridge admin API', version: '1' },
  });
  const paths = doc.paths as Record<string, Record<string, Operation>>;
  const byTag = new Map<string, string[]>();
  for (const [path, ops] of Object.entries(paths)) {
    for (const [method, op] of Object.entries(ops)) {
      const tag = op.tags?.[0] ?? 'other';
      const ok = op.responses?.['200'] ?? op.responses?.['201'];
      const status = op.responses?.['201'] !== undefined ? '201' : '200';
      const row = `| \`${method.toUpperCase()}\` | \`${path}\` | ${op.summary ?? ''} | ${fields(op.requestBody?.content?.['application/json']?.schema)} | ${status} ${typeOf(ok?.content?.['application/json']?.schema)} |`;
      byTag.set(tag, [...(byTag.get(tag) ?? []), row]);
    }
  }
  const lines = [
    '<!-- Generated by scripts/admin-api-reference.ts (pnpm docs:admin-api); do not edit. -->',
    '# Admin API reference',
    '',
    'Base path `/api/admin/v1`, served by `agility-bridge serve` when an admin token is configured',
    '(`AB_ADMIN_TOKEN_FILE`, from `agility-bridge admin-token`); without one every path answers `404`. Every request',
    'sends `Authorization: Bearer <admin token>`; bodies are JSON (at most 64 KiB). The OpenAPI 3.1 document is at',
    '`/api/admin/v1/openapi.json`.',
    '',
    'Errors use one envelope, `{ "error": { "code", "message", "field"? } }`: `400 bad_request`, `401 unauthorized`,',
    '`403 forbidden`, `404 not_found`, `409 conflict`, `413 payload_too_large`, `415 unsupported_media_type`,',
    '`422 invalid_input` (with the `field`), `429 rate_limited`, `502 upstream`, `503 unavailable`.',
    '',
    'Secrets are accepted once and never returned: credential tokens appear only as a 4-character hint, device tokens',
    'only in the response that issues them. Every change is written to the [audit log](../guide/audit-log.md).',
    'Owner-only: changing an instance origin (with a recent sign-in), creating or changing owners and admins, write',
    'settings and write tools. Personal Agility tokens are stored only by their own user.',
    '',
  ];
  for (const [tag, rows] of [...byTag].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(
      `## ${tag}`,
      '',
      '| Method | Path | What | Body | Response |',
      '|---|---|---|---|---|',
      ...rows,
      '',
    );
  }
  const schemas = (doc.components?.schemas ?? {}) as Record<string, Schema>;
  lines.push('## Objects', '');
  for (const [name, schema] of Object.entries(schemas).sort((a, b) => a[0].localeCompare(b[0]))) {
    if (name === 'Error' || name === 'AuditEntry') continue;
    lines.push(`- **${name}**: ${fields(schema).replaceAll('<br>', ', ')}`);
  }
  lines.push('');
  return lines.join('\n');
}

if (import.meta.main) {
  writeFileSync(OUT, render());
  console.error('wrote docs/reference/admin-api.md');
}
