// P9-03: docs/reference/performance.md, the per-tool budget table, generated from the committed measurements
// (scripts/bench/perf-results.json: latency per mode and Workers CPU) and the CPU and request baseline of
// `pnpm bench:worker` (scripts/bench/worker-baseline.json), beside the declared cost of every tool in the registry.
// Run: pnpm docs:perf   Check (CI): scripts/test/perf-reference.test.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { CORE_TOOLS } from '../packages/core/src/index.ts';
import type { PerfRun } from './perf/latency.ts';
import type { CpuStats } from './perf/tail-cpu.ts';
import type { BenchResult } from './worker-bench.ts';

const OUT = new URL('../docs/reference/performance.md', import.meta.url);
const RESULTS = new URL('./bench/perf-results.json', import.meta.url);
const BASELINE = new URL('./bench/worker-baseline.json', import.meta.url);

export interface PerfResults {
  readonly date: string;
  readonly plan: string;
  readonly latencyModel: Record<string, number>;
  readonly stdio: PerfRun;
  readonly http: PerfRun;
  readonly workers: PerfRun;
  readonly workersCpu: Record<string, CpuStats>;
  /** Worker CPU of the first request of each tool right after a deploy is not kept; boot figures are in the guide. */
  readonly notes?: string[];
}

const dash = '—';
const lat = (run: PerfRun, tool: string) => {
  const s = run.warm[tool];
  return s === undefined ? dash : `${s.p50} / ${s.p95}`;
};

export function render(
  results: PerfResults = JSON.parse(readFileSync(RESULTS, 'utf8')) as PerfResults,
  baseline: BenchResult = JSON.parse(readFileSync(BASELINE, 'utf8')) as BenchResult,
): string {
  const rows = CORE_TOOLS.filter((t) => t.kind === 'read').map((t) => {
    const cold = baseline.requests[`tool cold: ${t.name}`];
    const warm = baseline.requests[`tool warm: ${t.name}`];
    const cpu = results.workersCpu[t.name];
    const node = baseline.ms[`tool warm: ${t.name}`];
    return (
      `| \`${t.name}\` | ${t.cost} | ${cold ?? dash} | ${warm ?? dash} | ` +
      `${lat(results.stdio, t.name)} | ${lat(results.http, t.name)} | ${lat(results.workers, t.name)} | ` +
      `${cpu === undefined ? dash : `${cpu.cpuP50} / ${cpu.cpuP95}`} | ` +
      `${node === undefined ? dash : (node / baseline.calibrationMs).toFixed(1)} |`
    );
  });
  const cold = results.stdio.cold ?? {};
  const coldRows = CORE_TOOLS.filter((t) => t.kind === 'read' && cold[t.name] !== undefined).map(
    (t) => `| \`${t.name}\` | ${cold[t.name]?.ms} | ${cold[t.name]?.requests} |`,
  );
  return `<!-- Generated by scripts/perf-reference.ts from scripts/bench/perf-results.json and scripts/bench/worker-baseline.json: do not edit. Run \`pnpm docs:perf\`. -->

# Performance and cost per tool

> Measured ${results.date} (P9-03). **Synthetic and local-model numbers**, not a live Agility tenant: the upstream is the
> mock of \`scripts/perf/mock-agility.ts\` answering after a modelled delay (below), so latency is mostly
> *requests in sequence x the modelled delay*; what is firm is the request count and the CPU. How to read and repeat it:
> [Cloudflare limits](../guide/cloudflare-limits.md#measured-cost), [query limits](../guide/query-limits.md).

Latency model (ms per Agility request, from the P0-06 live measurements): ${Object.entries(
    results.latencyModel,
  )
    .map(([k, v]) => `${k} ${v}`)
    .join(', ')}.

## Per tool, worst-case fixture

Every read tool at the arguments of its worst-case fixture (\`packages/core/test/tools/worst-case.ts\`, L-114), ${results.http.n}
sequential warm calls per mode after one warm-up, metadata cached. *p50 / p95 in ms, client side* (the Worker column
includes the network from the machine that measured). Requests are Agility requests per call. **Declared** is the cost the
tool reports to the budget; **Cold** is the measured worst case on an empty metadata cache (what the declared cost must
cover); **Warm** with metadata cached. *Workers CPU* is the \`wrangler tail\` CPU time of a warm call on the ${results.plan}
plan; *Node CPU* is the warm call in \`pnpm bench:worker\`, as a multiple of its calibration workload. A dash: not offered
in that mode (a report above the Free budget of 45, or a tool a mode does not run).

| Tool | Declared | Cold | Warm | Node stdio | Node HTTP | Workers | Workers CPU ms | Node CPU (x cal.) |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Cold first call (Node stdio, fresh process)

The first call of a new process reads metadata from Agility (a Worker keeps parsed types in D1 across isolates, so its cold
call reads D1 rather than Agility).

| Tool | ms | Agility requests |
|---|---|---|
${coldRows.join('\n')}
`;
}

if (process.argv[1] === new URL(import.meta.url).pathname) writeFileSync(OUT, render());
